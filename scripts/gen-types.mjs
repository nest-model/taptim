#!/usr/bin/env node
// Generates src/lib/database.types.ts (Supabase-compatible `Database` type) by introspecting
// a database that has all migrations applied. Usage:
//   DATABASE_URL=... node scripts/gen-types.mjs
// Equivalent to `supabase gen types typescript`, usable without Docker.
import { writeFileSync } from 'node:fs';
import pg from 'pg';

const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();

const q = async (sql, params) => (await client.query(sql, params)).rows;

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
   where n.nspname = 'public' group by t.typname order by t.typname`);
const enumNames = new Set(enums.map((e) => e.name));

const SCALARS = {
  uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', citext: 'string',
  int2: 'number', int4: 'number', int8: 'number', float4: 'number', float8: 'number', numeric: 'number',
  bool: 'boolean', json: 'Json', jsonb: 'Json', date: 'string', timestamptz: 'string', timestamp: 'string',
  interval: 'string', tsvector: 'unknown', void: 'undefined', regconfig: 'string',
};

function tsType(typname) {
  if (typname.startsWith('_')) return `${tsType(typname.slice(1))}[]`;
  if (enumNames.has(typname)) return `Database["public"]["Enums"]["${typname}"]`;
  return SCALARS[typname] ?? 'unknown';
}

const relations = await q(`
  select c.oid, c.relname, c.relkind from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r', 'v') order by c.relname`);

async function columns(oid) {
  return q(`
    select a.attname as name, t.typname as type, not a.attnotnull as nullable,
           (a.atthasdef or a.attidentity <> '') as has_default,
           a.attgenerated <> '' as generated, a.attidentity = 'a' as identity_always
      from pg_attribute a join pg_type t on t.oid = a.atttypid
     where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped order by a.attnum`, [oid]);
}

const out = [];
out.push('// AUTO-GENERATED by scripts/gen-types.mjs — do not edit by hand.');
out.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];');
out.push('');
out.push('export type Database = {');
out.push('  public: {');

for (const kind of ['r', 'v']) {
  out.push(kind === 'r' ? '    Tables: {' : '    Views: {');
  for (const rel of relations.filter((r) => r.relkind === kind)) {
    const cols = await columns(rel.oid);
    out.push(`      ${rel.relname}: {`);
    out.push('        Row: {');
    for (const c of cols) {
      // views report every column as nullable; keep it honest
      out.push(`          ${c.name}: ${tsType(c.type)}${c.nullable || kind === 'v' ? ' | null' : ''};`);
    }
    out.push('        };');
    if (kind === 'r') {
      out.push('        Insert: {');
      for (const c of cols) {
        if (c.generated || c.identity_always) out.push(`          ${c.name}?: never;`);
        else out.push(`          ${c.name}${c.nullable || c.has_default ? '?' : ''}: ${tsType(c.type)}${c.nullable ? ' | null' : ''};`);
      }
      out.push('        };');
      out.push('        Update: {');
      for (const c of cols) {
        if (c.generated || c.identity_always) out.push(`          ${c.name}?: never;`);
        else out.push(`          ${c.name}?: ${tsType(c.type)}${c.nullable ? ' | null' : ''};`);
      }
      out.push('        };');
    }
    out.push('        Relationships: [];');
    out.push('      };');
  }
  out.push('    };');
}

const fns = await q(`
  select p.proname as name, p.proretset as retset, rt.typname as rettype, rt.typtype as rettypetype,
         rt.typrelid as retrelid, p.pronargdefaults as ndefaults,
         coalesce(p.proargnames, '{}') as argnames, coalesce(p.proargmodes::text[], '{}') as argmodes,
         (select array_agg(t.typname::text order by o.ord) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality o(oid, ord)
            join pg_type t on t.oid = o.oid) as argtypes
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
   where n.nspname = 'public' and p.prokind = 'f' and rt.typname <> 'trigger'
     and (has_function_privilege('authenticated', p.oid, 'execute') or has_function_privilege('anon', p.oid, 'execute'))
   order by p.proname`);

out.push('    Functions: {');
for (const f of fns) {
  const modes = f.argmodes.length ? f.argmodes : f.argtypes?.map(() => 'i') ?? [];
  const ins = [];
  const outs = [];
  (f.argtypes ?? []).forEach((t, i) => {
    const entry = { name: f.argnames[i], type: t };
    if (modes[i] === 't' || modes[i] === 'o') outs.push(entry);
    else ins.push(entry);
  });
  const firstOptional = ins.length - f.ndefaults;
  const args = ins.length
    ? `{ ${ins.map((a, i) => `${a.name}${i >= firstOptional ? '?' : ''}: ${tsType(a.type)}`).join('; ')} }`
    : 'Record<PropertyKey, never>';
  let ret;
  if (outs.length) ret = `{ ${outs.map((o) => `${o.name}: ${tsType(o.type)} | null`).join('; ')} }[]`;
  else if (f.rettypetype === 'c') {
    const rel = relations.find((r) => r.oid === f.retrelid);
    ret = `Database["public"]["${rel.relkind === 'v' ? 'Views' : 'Tables'}"]["${rel.relname}"]["Row"]${f.retset ? '[]' : ''}`;
  } else ret = `${tsType(f.rettype)}${f.retset ? '[]' : ''}`;
  out.push(`      ${f.name}: { Args: ${args}; Returns: ${ret} };`);
}
out.push('    };');

out.push('    Enums: {');
for (const e of enums) out.push(`      ${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(' | ')};`);
out.push('    };');
out.push('    CompositeTypes: { [_ in never]: never };');
out.push('  };');
out.push('};');
out.push('');
out.push('type PublicSchema = Database["public"];');
out.push('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];');
out.push('export type Views<T extends keyof PublicSchema["Views"]> = PublicSchema["Views"][T]["Row"];');
out.push('export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];');
out.push('');

writeFileSync(new URL('../src/lib/database.types.ts', import.meta.url), out.join('\n'));
await client.end();
console.log(`database.types.ts: ${relations.length} relations, ${fns.length} functions, ${enums.length} enums`);
